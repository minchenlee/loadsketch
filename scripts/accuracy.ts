// Generates docs/accuracy.md from the shared accuracy suite (tests/accuracy-cases.ts).
// --check: exit 1 when docs/accuracy.md is missing or differs from a fresh run.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { measureAllAccuracyCases, type AccuracyMeasurement } from '../tests/accuracy-cases.ts';

const root = join(import.meta.dirname, '..');
const outFile = join(root, 'docs', 'accuracy.md');

function fmtValue(val: number, unit: AccuracyMeasurement['unit']): string {
  switch (unit) {
    case 'ms':
      return `${val.toFixed(2)} ms`;
    case 'rps':
      return `${val.toFixed(2)} rps`;
    case 'req/s':
      return `${val.toFixed(1)} req/s`;
    case 'ratio':
      return val.toFixed(4);
  }
}

function fmtError(rel: number): string {
  const pct = (rel * 100).toFixed(2);
  return `${rel >= 0 ? '+' : ''}${pct}%`;
}

export function renderAccuracyMd(results: AccuracyMeasurement[] = measureAllAccuracyCases()): string {
  const passed = results.filter((r) => r.status === 'pass').length;
  const deviations = results.filter((r) => r.status === 'known-deviation');
  const failed = results.filter((r) => r.status === 'fail');
  if (failed.length) {
    throw new Error(`Unexpected failing accuracy cases: ${failed.map((f) => f.id).join(', ')}`);
  }

  const lines: string[] = [
    '# Simulation accuracy against analytical theory',
    '',
    'Generated by `node scripts/accuracy.ts` from [`tests/accuracy-cases.ts`](../tests/accuracy-cases.ts) using fixed random seeds.',
    'loadsketch is a model for learning, not a capacity planning tool; these checks verify that the discrete-event engine agrees with closed-form queueing and reliability formulas on small, controlled designs.',
    '',
    `Summary: **${results.length} checks** (${passed} pass within tolerance, ${deviations.length} known ${deviations.length === 1 ? 'deviation' : 'deviations'}).`,
    '',
    '| Case | Theory | Simulated | Error | Tolerance | Status |',
    '|---|---|---|---:|---:|---|',
  ];

  for (const r of results) {
    const label = `${r.name} — ${r.metric}`;
    const status = r.status === 'pass' ? 'Pass' : 'Known deviation';
    lines.push(
      `| ${label} | ${fmtValue(r.expected, r.unit)} | ${fmtValue(r.actual, r.unit)} | ${fmtError(r.relError)} | ±${Math.round(r.tolerance * 100)}% | ${status} |`,
    );
  }

  lines.push('', '## Known deviations', '');
  for (const d of deviations) {
    lines.push(`- **${d.name} (${d.metric}):** ${d.knownDeviation!.reason}`);
  }
  lines.push(
    '- **Cache `ttlS` under scaling (`scale > 1`):** In `lru` mode with `ttlS > 0`, `scaleDesign()` reduces request arrivals by `k` while leaving `ttlS`, clock timestamps, `capacityKeys`, and the client key space unscaled. Each key therefore receives `1/k` as many requests per TTL window, increasing TTL expirations and under-predicting hit rate at `k > 1`: for `capacityKeys = 200`, `keys = { count: 500, zipf: 0.8 }`, and `5000 rps`, `ttlS = 1` with `readRatio = 1.0` drops hit rate from `0.680` (`k = 1`) to `0.623` (`k = 8`, `-0.058`), `ttlS = 1` with `readRatio = 0.9` differs by `-0.022`, and `ttlS = 10` differs by only `-0.003`. `ttlS` is not multiplied by `k` because engine time does not scale, so scaling `ttlS` would delay TTL expiry instants (such as synchronized stampedes) by `k`x; furthermore, a separate effect causes `ttlS = 0` with `readRatio = 0.9` to show a `+0.032` higher hit rate at `k = 8` (fewer concurrent reads arrive during refill after write invalidation), which scaling `ttlS` cannot fix. When TTL is short (~1 s) and hit rate accuracy matters, run at `scale = 1`.',
  );

  lines.push(
    '',
    '## Bottleneck attribution',
    '',
    '- **Blocking downstream transfer:** When the highest-scoring node rejected requests with `queue_full`, spent at least 2/3 of its slot busy time waiting on downstream calls within those rejection windows, and its longest-waiting downstream branch reached >= 0.95 utilization in the same windows, the reported bottleneck shifts to that downstream node (following routers or waiting intermediate tiers).',
    '- **Shared routers and intermediate tiers:** Outgoing edge wait is aggregated across all callers rather than per origin, so traversal can follow a saturated branch that the rejected upstream never calls if another caller saturates it in the same windows.',
    '- **Edge latency:** When upstream waiting comes mostly from edge network latency while another client saturates the downstream in the same windows, blame still transfers to that downstream.',
    '- **Parallel calls:** Only the single outgoing branch with the most cumulative wait in the rejection windows is followed; when parallel branches have nearly equal wait times, blame conservatively stays on the upstream.',
    '',
    '## Token-bucket burst under scaling',
    '',
    'Token-bucket `rate_limiter` burst scaling (`scaleDesign()` in `src/engine/scale.ts`) chooses between two rules based on the scenario events and refill time (`BURST_REFILL_MAX_S = 1`):',
    '',
    '- **Rule:** When the scenario contains **no** spike-like events (`spike`, `ramp`, `wave`, `cron`) **and** the bucket refills quickly (`ratePerSec > 0` and `burst / ratePerSec <= 1` s), `burst` uses `max(min(origBurst, 32), round(origBurst / k))`. Otherwise (any `spike`/`ramp`/`wave`/`cron` event is present, or `ratePerSec === 0`, or `burst / ratePerSec > 1` s), `burst` divides linearly: `max(1, round(origBurst / k))`.',
    '- **Why two regimes cannot both be exact:** At `scale = k`, each scaled token represents `k` real tokens. Dividing `burst` by `k` (clamped at `1`) preserves the real-request volume allowed before rejection during concentrated bursts (`spike`/`cron`) or slow/zero-refill drains (`burst / ratePerSec > 1` s), whereas a `32`-token floor would admit up to `32 * k` real requests per burst. Conversely, for fast-refilling steady Poisson traffic (`burst / ratePerSec <= 1` s) with small buckets (e.g. `burst = 4`), dividing to `1` causes spurious rejections on normal inter-arrival variance at `1/k` rate, so the `min(origBurst, 32)` floor is needed to match `k = 1` steady rejection rates.',
    '- **Measured comparison (`k = 1` vs `k = 8`):**',
    '  - Steady Poisson (`ratePerSec = 800`, `burst = 4`, no events, `30 s`): at `600` rps, error rate `0.0483` (`k = 1`) vs `0.0430` (`k = 8`); at `750` rps, `0.1056` (`k = 1`) vs `0.1034` (`k = 8`); with `burst = 400` at `600` rps, `0.0000` (`k = 1`) vs `0.0000` (`k = 8`).',
    '  - Short spike / cron bursts (`ratePerSec = 800`, `burst = 32`): `cron` (`10` rps base, every `1` s an `800x` burst for `10 ms`, `30 s`) gives error rate `0.4584` at `k = 1` vs `0.5329` at `k = 8` (`1420` vs `1192` ok); `spike` (`100` rps base, `50x` for `0.1 s` in `1 s`) gives error rate `0.6610` at `k = 1` vs `0.5522` at `k = 8` (`199` vs `240` ok).',
    '  - Slow / zero refill (`100` rps over `5 s`, no events, `burst = 32`): `ratePerSec = 0` gives error rate `0.9369` at `k = 1` vs `0.9273` at `k = 8` (`32` vs `32` ok); `ratePerSec = 1` gives error rate `0.9290` at `k = 1` vs `0.9273` at `k = 8` (`36` vs `32` ok).',
    '- **Known limitations:**',
    '  - **(a) Event-free correlated bursts:** Correlated request bursts that do not come from `spike`/`ramp`/`wave`/`cron` events — such as retry storms after recovery, queue/channel drains after `pause`, or upstream batched dispatches — still receive the `min(burst, 32)` floor when `burst / ratePerSec <= 1` s and can be under-rejected under scaling.',
    '  - **(b) Steady segments alongside a spike event:** Because `hasSpikes` is computed once per simulation across all scenario events, any scenario containing a `spike`/`ramp`/`wave`/`cron` reverts every `rate_limiter` to `max(1, round(burst / k))` for the entire run, so steady sub-second segments with small `burst` (e.g. `burst = 4`) will over-reject during quiet periods.',
    '  - **(c) Slow `ramp` or `wave` scenarios:** Smooth, slow `ramp` or `wave` events are included in `SPIKE_EVENTS` and therefore also trigger (b), reverting all limiters to `max(1, round(burst / k))`. Run at `scale = 1` when exact small-burst steady rejection and transient spike/ramp behavior both matter in the same run.',
    '  - **(d) Starting bucket:** A rate limiter starts full. When the `min(burst, 32)` floor applies, the initial tokens represent `min(burst, 32) * k` real requests instead of `min(burst, 32)` (an extra `~32 * (k - 1)` admitted requests once at t = 0). On short runs with `warmupS = 0`, manual large `scale`, and offered rate above `ratePerSec`, initial error rate is under-reported (e.g. `2000` rps for `1 s`, `ratePerSec = 800`, `burst = 32`, `warmupS = 0`, `seed = 1`, no station `k` cap: error rate `58.2%` at `k = 1`, `46.5%` at `k = 8`, `0.0%` at `k = 100`). Under automatic scaling (`scale = \'auto\'`), `k > 1` requires `~300k * k` expected requests so the one-time excess is under `0.01%` (this `1 s` case stays at `k = 1`), and runs with sufficient warmup (`warmupS > 0`) drain the starting bucket before measurement begins.',
    '',
    '## What this table does not prove',
    '',
    '- **Real product internals:** Components represent generic abstractions (a generic database, cache, or queue), not PostgreSQL, Redis, or Kafka, and omit engine-specific details such as MVCC/VACUUM, lock managers, or protocol serialization.',
    '- **Network, OS, and hardware limits:** Packet framing, TCP congestion control, bandwidth caps, memory pressure, disk I/O contention, and CPU core scheduling are not modeled.',
    '- **Absolute production sizing:** Agreement with idealized Poisson and exponential formulas does not mean an absolute latency or throughput number from a simulation run can size a production system. Real workloads have correlated bursts, heavy-tailed payloads, and code-level bottlenecks.',
    '- **Arbitrary feature combinations:** Most checks above isolate one mechanism at a time (single station, bounded queue, two-stage series, retries, load balancing, scaling, or timeouts). Complex interactions across many mechanisms together are tested behaviourally rather than against closed-form equations.',
    '- **Data correctness:** Counters track stale reads, lost writes, and dual-write gaps, not payload contents or conflict-resolution logic.',
    '',
  );

  return lines.join('\n');
}

if (import.meta.main ?? process.argv[1] === import.meta.filename) {
  const check = process.argv.includes('--check');
  const want = Buffer.from(renderAccuracyMd(), 'utf8');
  if (check) {
    let now: Buffer | null = null;
    try {
      now = readFileSync(outFile);
    } catch {}
    if (!now || !now.equals(want)) {
      console.error(`${relative(root, outFile)} is out of date: run node scripts/accuracy.ts`);
      process.exit(1);
    }
    console.log(`${relative(root, outFile)}: up to date`);
  } else {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(outFile, want);
    console.log(`${relative(root, outFile)}: ${want.length} bytes`);
  }
}
