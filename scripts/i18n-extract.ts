// Collects every message id and writes src/i18n/en.ts, keeping the translations already there.
// Sources: t('…') and tx('…') calls in src and cli, the component specs (KINDS) and the examples.
// Run: node scripts/i18n-extract.ts [--check]   (--check: exit 1 if en.ts would change)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATEGORY_LABEL, EDGE_PARAMS, KINDS } from '../src/schema/kinds.ts';
import { EN } from '../src/i18n/en.ts';

const root = join(import.meta.dirname, '..');
const ids = new Set<string>();
const add = (s: unknown) => {
  if (typeof s === 'string' && /[一-鿿\u3000-\u303f\uff00-\uffef]/.test(s)) ids.add(s);
};

function walk(dir: string, out: string[]): string[] {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(ts|tsx)$/.test(f) && !p.endsWith(join('i18n', 'en.ts'))) out.push(p);
  }
  return out;
}

// t('…'), t("…"), t(`…`) and tx(…): the first argument must be a plain literal
const CALL = /\btx?\(\s*('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\$]|\\.)*`)/g;
const unquote = (lit: string) => {
  const body = lit.slice(1, -1);
  return body.replace(/\\(.)/g, (_, c: string) => (c === 'n' ? '\n' : c));
};
const files = [...walk(join(root, 'src'), []), ...walk(join(root, 'cli'), [])];
let bad = 0;
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  for (const m of src.matchAll(CALL)) add(unquote(m[1]));
  // a t() whose first argument is not a literal cannot be extracted
  for (const m of src.matchAll(/\bt\(\s*`[^`]*\$\{/g)) {
    console.error(`${f}: t() with an interpolated template; use {name} placeholders: ${m[0]}`);
    bad++;
  }
}

for (const c of Object.values(CATEGORY_LABEL)) add(c);
const paramSets = [...Object.values(KINDS).map((k) => k.params), EDGE_PARAMS];
for (const k of Object.values(KINDS)) {
  add(k.label);
  add(k.summary);
}
for (const params of paramSets) {
  for (const p of Object.values(params)) {
    const ps = p as { label?: string; help?: string; options?: { label?: string; hint?: string }[] };
    add(ps.label);
    add(ps.help);
    for (const o of ps.options ?? []) {
      add(o.label);
      add(o.hint);
    }
  }
}

for (const dir of ['examples/designs', 'examples/scenarios']) {
  for (const f of readdirSync(join(root, dir))) {
    if (!f.endsWith('.json')) continue;
    const j = JSON.parse(readFileSync(join(root, dir, f), 'utf8'));
    add(j.name);
    add(j.description);
    for (const n of j.nodes ?? []) add(n.label);
    for (const n of j.notes ?? []) add(n.text);
  }
}

const sorted = [...ids].sort();
const kept = Object.keys(EN).filter((k) => ids.has(k)).length;
const dropped = Object.keys(EN).filter((k) => !ids.has(k));
const lines = sorted.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(EN[k] ?? '')},`);
const text = `// English catalog: Chinese message id → English. Keys are generated by scripts/i18n-extract.ts;\n// values are edited by hand. An empty value falls back to the Chinese text.\nexport const EN: Record<string, string> = {\n${lines.join('\n')}\n};\n`;
const path = join(root, 'src/i18n/en.ts');
const missing = sorted.filter((k) => !EN[k]).length;
if (process.argv.includes('--check')) {
  const same = readFileSync(path, 'utf8') === text;
  console.log(`${sorted.length} messages, ${missing} without English${same ? '' : ', en.ts is out of date'}`);
  process.exit(same && !bad ? 0 : 1);
}
writeFileSync(path, text);
console.log(`${sorted.length} messages (${kept} translated kept, ${missing} without English, ${dropped.length} dropped)`);
if (bad) process.exit(1);
